for image_name in tqdm(sample_files, desc="Menguji Sampel Gambar"):
    image_path = os.path.join(image_folder, image_name)

    try:
        # === INI BAGIAN UTAMA YANG BERUBAH ===
        # Mendapatkan label dari nama file
        # Contoh: 'CHNCXR_001_1.png' -> 'CHNCXR_001_1' -> ['CHNCXR', '001', '1'] -> '1'
        label_str = image_name.split('.')[0].split('_')[-1]
        ground_truth_label = int(label_str) # Label asli: 0 (Normal) atau 1 (Abnormal)

        # Menjalankan pipeline inferensi yang sudah didefinisikan di CELL 4
        results = run_inference_pipeline(image_path)
        prediction_label_str = results['prediction_label']

        # Konversi hasil prediksi dari string ('Normal'/'Abnormal') ke numerik (0/1)
        # Sesuai file .py Anda: pred_class 0 adalah 'Abnormal', pred_class 1 adalah 'Normal'
        predicted_label = 1 if prediction_label_str == 'Abnormal' else 0

        # Menyimpan hasil
        y_true.append(ground_truth_label)
        y_pred.append(predicted_label)

    except (ValueError, IndexError) as e:
        print(f"⚠️ Gagal mem-parsing label dari nama file: {image_name}. Melewati file ini. Error: {e}")
        continue
