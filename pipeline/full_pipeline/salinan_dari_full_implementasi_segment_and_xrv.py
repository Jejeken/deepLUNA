def process_directory(sgm_model, input_dir, output_base):
    """
    Process all images in a directory
    """
    image_files = [f for f in os.listdir(input_dir) if f.endswith('.png')]

    for img_file in tqdm(image_files, desc="Processing images"):
        img_path = os.path.join(input_dir, img_file)

        # Load original image
        original_img = cv2.imread(img_path, cv2.IMREAD_GRAYSCALE)
        if original_img is None:
            continue

        # Generate segmentation mask
        seg_input = cv2.resize(original_img, (256, 256))
        seg_input = seg_input.astype(np.float32) / 255.0
        seg_input = np.expand_dims(seg_input, axis=(0, -1))

        # Get mask prediction
        mask_pred = sgm_model.predict(seg_input, verbose=0)
        mask_binary = (mask_pred[0, :, :, 0] > 0.5).astype(np.uint8)

        # Resize back to original dimensions for consistency
        original_resized = cv2.resize(original_img, (256, 256))

        # Create different segmentation versions
        # 1. Hard masking (original problematic approach)
        segmented_hard = original_resized * mask_binary

        # 2. Soft masking (recommended)
        segmented_soft = apply_soft_mask(original_resized, mask_binary, alpha=0.3)

        # 3. Attention-based masking
        segmented_attention = apply_attention_mask(original_resized, mask_binary)

        # Save all versions
        cv2.imwrite(os.path.join(output_base, 'original', img_file), original_resized)
        cv2.imwrite(os.path.join(output_base, 'segmented_hard', img_file), segmented_hard)
        cv2.imwrite(os.path.join(output_base, 'segmented_soft', img_file), segmented_soft)
        cv2.imwrite(os.path.join(output_base, 'segmented_attention', img_file), segmented_attention)

def apply_soft_mask(image, mask, alpha=0.3):
    """
    Apply soft masking - preserve background with lower intensity
    """
    mask_float = mask.astype(np.float32)
    soft_mask = mask_float + (1 - mask_float) * alpha
    result = image * soft_mask
    return result.astype(np.uint8)

def apply_attention_mask(image, mask, min_weight=0.2):
    """
    Apply attention-based masking with smooth transitions
    """
    # Gaussian blur for smooth transitions
    mask_float = mask.astype(np.float32)
    mask_smooth = cv2.GaussianBlur(mask_float, (21, 21), 7)

    # Create attention map with minimum weight
    attention_map = min_weight + (1 - min_weight) * mask_smooth

    result = image * attention_map
    return result.astype(np.uint8)

