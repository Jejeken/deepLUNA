class AugmentedChestXRayDataset(Dataset):
    """
    Dataset that combines original and segmented images for training
    """
    def __init__(self, base_dir, mode='train', segmentation_type='soft',
                 transform=None, augment_strategy='both'):
        """
        Args:
            base_dir: Base directory containing train/test folders
            mode: 'train' or 'test'
            segmentation_type: 'hard', 'soft', or 'attention'
            transform: Augmentation transforms
            augment_strategy: 'both', 'original', 'segmented', or 'mixed'
        """
        self.base_dir = os.path.join(base_dir, mode)
        self.segmentation_type = segmentation_type
        self.transform = transform
        self.augment_strategy = augment_strategy

        self.image_paths = []
        self.labels = []

        # Load file paths based on strategy
        original_dir = os.path.join(self.base_dir, 'original')
        segmented_dir = os.path.join(self.base_dir, f'segmented_{segmentation_type}')

        # Get all image files
        image_files = [f for f in os.listdir(original_dir) if f.endswith('.png')]

        for filename in image_files:
            # Extract label from filename
            if '_0.png' in filename:
                label = 0  # Normal
            elif '_1.png' in filename:
                label = 1  # Abnormal
            else:
                label = 1  # Default to abnormal

            if augment_strategy == 'both':
                # Add both original and segmented versions
                self.image_paths.append((os.path.join(original_dir, filename), 'original'))
                self.labels.append(label)
                self.image_paths.append((os.path.join(segmented_dir, filename), 'segmented'))
                self.labels.append(label)

            elif augment_strategy == 'original':
                self.image_paths.append((os.path.join(original_dir, filename), 'original'))
                self.labels.append(label)

            elif augment_strategy == 'segmented':
                self.image_paths.append((os.path.join(segmented_dir, filename), 'segmented'))
                self.labels.append(label)

            elif augment_strategy == 'mixed':
                # Randomly choose between original and segmented
                if np.random.random() > 0.5:
                    self.image_paths.append((os.path.join(original_dir, filename), 'original'))
                else:
                    self.image_paths.append((os.path.join(segmented_dir, filename), 'segmented'))
                self.labels.append(label)

        # Calculate class weights
        self.class_counts = np.bincount(self.labels)
        self.class_weights = 1.0 / (self.class_counts + 1e-6)

        print(f"Dataset initialized: {len(self.image_paths)} samples")
        print(f"Strategy: {augment_strategy}, Segmentation: {segmentation_type}")
        print(f"Class distribution: Normal={self.class_counts[0]}, Abnormal={self.class_counts[1]}")

    def __len__(self):
        return len(self.image_paths)

    def __getitem__(self, idx):
        img_path, img_type = self.image_paths[idx]
        label = self.labels[idx]

        # Load image
        image = cv2.imread(img_path, cv2.IMREAD_GRAYSCALE)
        if image is None:
            image = np.zeros((256, 256), dtype=np.uint8)

        # Apply transforms
        if self.transform:
            image = self.transform(image)

        return image, label, img_type

