def train_augmented_classifier(sgm_model, cxr_dir, test_dir,
                              segmentation_type='soft',
                              augment_strategy='both',
                              num_epochs=30,
                              batch_size=16):
    """
    Complete training pipeline for augmented classifier
    """
    print("="*70)
    print("🚀 STARTING AUGMENTED CLASSIFIER TRAINING")
    print("="*70)

    # Step 1: Create segmented dataset
    segmented_dataset_dir = create_segmented_dataset(sgm_model, cxr_dir, test_dir)

    # Step 2: Setup transforms
    train_transform = AdvancedXRayTransforms(is_training=True)
    val_transform = AdvancedXRayTransforms(is_training=False)

    # Step 3: Create datasets
    print("\n📊 Creating augmented datasets...")
    train_dataset = AugmentedChestXRayDataset(
        segmented_dataset_dir,
        mode='train',
        segmentation_type=segmentation_type,
        transform=train_transform,
        augment_strategy=augment_strategy
    )

    test_dataset = AugmentedChestXRayDataset(
        segmented_dataset_dir,
        mode='test',
        segmentation_type=segmentation_type,
        transform=val_transform,
        augment_strategy='mixed'  # Test with mixed strategy
    )

    # Split training data for validation
    val_size = int(0.2 * len(train_dataset))
    train_size = len(train_dataset) - val_size
    train_subset, val_subset = random_split(train_dataset, [train_size, val_size])

    # Create dataloaders
    train_loader = DataLoader(train_subset, batch_size=batch_size, shuffle=True,
                            num_workers=4, pin_memory=True)
    val_loader = DataLoader(val_subset, batch_size=batch_size, shuffle=False,
                          num_workers=4, pin_memory=True)
    test_loader = DataLoader(test_dataset, batch_size=batch_size, shuffle=False,
                           num_workers=4, pin_memory=True)

    print(f"📊 Dataset sizes:")
    print(f"  Training: {len(train_subset)} samples")
    print(f"  Validation: {len(val_subset)} samples")
    print(f"  Test: {len(test_dataset)} samples")

    # Step 4: Initialize model
    print("\n🏗️ Initializing Multi-Input Classifier...")
    model = MultiInputClassifier(dropout=0.5).to(device)

    # Step 5: Setup training components
    criterion = nn.CrossEntropyLoss(weight=torch.tensor(train_dataset.class_weights).to(device))

    # Two-stage training
    # Stage 1: Train classifier head only
    print("\n📍 Stage 1: Training classifier head (15 epochs)")
    for param in model.backbone.parameters():
        param.requires_grad = False

    optimizer_stage1 = torch.optim.AdamW(
        filter(lambda p: p.requires_grad, model.parameters()),
        lr=1e-3, weight_decay=0.01
    )

    best_val_acc = 0
    for epoch in range(15):
        train_loss, train_acc = train_augmented_epoch(
            model, train_loader, criterion, optimizer_stage1, device, epoch + 1
        )
        val_loss, val_acc, _, _ = validate_augmented_epoch(
            model, val_loader, criterion, device
        )

        print(f"Epoch {epoch+1}/15 - Train: {train_acc:.2f}%, Val: {val_acc:.2f}%")

        if val_acc > best_val_acc:
            best_val_acc = val_acc
            torch.save(model.state_dict(), 'best_augmented_model_stage1.pth')

    # Stage 2: Fine-tune entire model
    print("\n📍 Stage 2: Fine-tuning entire model (15 epochs)")
    for param in model.backbone.parameters():
        param.requires_grad = True

    optimizer_stage2 = torch.optim.AdamW([
        {'params': model.backbone.parameters(), 'lr': 1e-5},
        {'params': model.attention.parameters(), 'lr': 5e-5},
        {'params': model.classifier.parameters(), 'lr': 1e-4}
    ], weight_decay=0.01)

    for epoch in range(15):
        train_loss, train_acc = train_augmented_epoch(
            model, train_loader, criterion, optimizer_stage2, device, epoch + 16
        )
        val_loss, val_acc, val_preds, val_labels = validate_augmented_epoch(
            model, val_loader, criterion, device
        )

        print(f"Epoch {epoch+16}/30 - Train: {train_acc:.2f}%, Val: {val_acc:.2f}%")

        if val_acc > best_val_acc:
            best_val_acc = val_acc
            torch.save(model.state_dict(), 'best_augmented_model_final.pth')

# Step 6: Final evaluation
    print("\n🧪 Final Evaluation on Test Set...")
    model.load_state_dict(torch.load('best_augmented_model_final.pth'))
    test_loss, test_acc, test_preds, test_labels = validate_augmented_epoch(
        model, test_loader, criterion, device
    )

    # Print results
    print("\n" + "="*60)
    print("🎉 TRAINING COMPLETE - FINAL RESULTS")
    print("="*60)
    print(f"✅ Best Validation Accuracy: {best_val_acc:.2f}%")
    print(f"🎯 Test Accuracy: {test_acc:.2f}%")

    # Classification report
    print("\n📊 Classification Report:")
    print(classification_report(test_labels, test_preds,
                              target_names=['Normal', 'Abnormal']))

    # Confusion matrix
    cm = confusion_matrix(test_labels, test_preds)
    plt.figure(figsize=(8, 6))
    sns.heatmap(cm, annot=True, fmt='d', cmap='Blues',
                xticklabels=['Normal', 'Abnormal'],
                yticklabels=['Normal', 'Abnormal'])
    plt.title(f'Test Confusion Matrix - Augmented Training\nAccuracy: {test_acc:.2f}%')
    plt.ylabel('True Label')
    plt.xlabel('Predicted Label')
    plt.show()

    return model, test_acc

