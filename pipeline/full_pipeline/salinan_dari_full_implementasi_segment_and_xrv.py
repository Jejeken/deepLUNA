class MultiInputClassifier(nn.Module):
    """
    Enhanced classifier that can handle both original and segmented inputs
    with learned weighting between them
    """
    def __init__(self, backbone_name="densenet121-res224-all", num_classes=2, dropout=0.5):
        super(MultiInputClassifier, self).__init__()

        # Shared backbone
        self.backbone = xrv.models.DenseNet(weights=backbone_name)

        # Get feature dimensions
        with torch.no_grad():
            dummy_input = torch.randn(1, 1, 224, 224)
            backbone_features = self.backbone.features(dummy_input)
            num_features = backbone_features.shape[1]

        # Type embedding to distinguish between original and segmented
        self.type_embedding = nn.Embedding(2, num_features)  # 0: original, 1: segmented

        # Attention mechanism
        self.attention = nn.Sequential(
            nn.AdaptiveAvgPool2d(1),
            nn.Flatten(),
            nn.Linear(num_features, num_features // 16),
            nn.ReLU(),
            nn.Linear(num_features // 16, num_features),
            nn.Sigmoid()
        )

        # Enhanced classifier
        self.global_pool = nn.AdaptiveAvgPool2d(1)
        self.global_max_pool = nn.AdaptiveMaxPool2d(1)

        self.classifier = nn.Sequential(
            nn.Dropout(dropout),
            nn.Linear(num_features * 2 + num_features, 512),  # +num_features for type embedding
            nn.BatchNorm1d(512),
            nn.ReLU(inplace=True),
            nn.Dropout(dropout),
            nn.Linear(512, 256),
            nn.BatchNorm1d(256),
            nn.ReLU(inplace=True),
            nn.Dropout(dropout),
            nn.Linear(256, num_classes)
        )

        # Learnable weights for combining original and segmented features
        self.feature_weights = nn.Parameter(torch.ones(2) * 0.5)

        self.backbone.classifier = nn.Identity()

    def forward(self, x, input_type=None):
        """
        Args:
            x: Input image tensor
            input_type: 0 for original, 1 for segmented, None for unknown
        """
        # Extract features
        features = self.backbone.features(x)

        # Apply attention
        attention_weights = self.attention(features)
        attention_weights = attention_weights.unsqueeze(-1).unsqueeze(-1)
        attended_features = features * attention_weights

        # Multi-scale pooling
        avg_pool = self.global_pool(attended_features)
        max_pool = self.global_max_pool(attended_features)

        # Combine pooled features
        combined = torch.cat([avg_pool, max_pool], dim=1)
        combined = torch.flatten(combined, 1)

        # Add type embedding if available
        if input_type is not None:
            batch_size = x.size(0)
            type_emb = self.type_embedding(input_type)
            combined = torch.cat([combined, type_emb], dim=1)
        else:
            # Use zero embedding if type unknown
            batch_size = x.size(0)
            zero_emb = torch.zeros(batch_size, self.type_embedding.embedding_dim).to(x.device)
            combined = torch.cat([combined, zero_emb], dim=1)

        # Classification
        logits = self.classifier(combined)
        return logits

