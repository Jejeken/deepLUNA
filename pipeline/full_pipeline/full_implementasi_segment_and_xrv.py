class AdvancedXRayTransforms:
    """Advanced transforms for classification model input"""
    def __init__(self, image_size=224):
        self.image_size = image_size
        self.transform = A.Compose([
            A.Resize(self.image_size, self.image_size),
            A.Normalize(mean=[0.5], std=[0.5]),  # Normalize to [-1, 1]
            ToTensorV2(),
        ])

    def __call__(self, image):
        if isinstance(image, np.ndarray):
            if len(image.shape) == 3:
                image = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)
        else:
            image = np.array(image)

        # Apply CLAHE preprocessing
        clahe = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(8,8))
        image = clahe.apply(image)

        transformed = self.transform(image=image)
        return transformed['image']

def run_inference_pipeline(image_path):
    """
    End-to-end inference pipeline for CXR analysis

    Args:
        image_path: Path to the input chest X-ray image

    Returns:
        dict: Contains all pipeline artifacts and results
    """
    print(f"🔄 Processing image: {image_path}")

    # Step 1: Load and preprocess image for segmentation
    print("📖 Loading original image...")
    original_img = cv2.imread(image_path, cv2.IMREAD_GRAYSCALE)
    if original_img is None:
        raise ValueError(f"Could not load image from {image_path}")

    # Resize and normalize for segmentation model (256x256, [0,1])
    print("🔧 Preprocessing for segmentation...")
    seg_input = cv2.resize(original_img, (256, 256))
    seg_input = seg_input.astype(np.float32) / 255.0
    seg_input = np.expand_dims(seg_input, axis=(0, -1))  # Shape: (1, 256, 256, 1)

    # Step 2: Run segmentation inference
    print("🫁 Running lung segmentation...")
    mask_pred = sgm_model.predict(seg_input, verbose=0)
    mask_binary = (mask_pred[0, :, :, 0] > 0.5).astype(np.uint8)

    # Step 3: Apply mask to original image
    print("✂️ Applying mask to extract lung regions...")
    original_resized = cv2.resize(original_img, (256, 256))
    segmented_img = original_resized * mask_binary

    # Step 4: Preprocess segmented image for classification
    print("🔧 Preprocessing for classification...")
    clf_transform = AdvancedXRayTransforms(image_size=224)
    clf_input = clf_transform(segmented_img)
    clf_input = clf_input.unsqueeze(0).to(device)  # Add batch dimension

    # Step 5: Run classification inference
    print("🔍 Running binary classification...")
    with torch.no_grad():
        clf_output = clf_model(clf_input)
        clf_probs = torch.nn.functional.softmax(clf_output, dim=1)
        pred_class = clf_output.argmax(1).item()
        confidence = clf_probs.max(1)[0].item()

    # Step 6: Prepare results
    class_names = ['Normal', 'Abnormal']
    prediction_label = class_names[pred_class]

    results = {
        'original_image': original_img,
        'original_resized': original_resized,
        'segmentation_mask': mask_binary,
        'segmented_image': segmented_img,
        'clf_input_tensor': clf_input,
        'prediction_class': pred_class,
        'prediction_label': prediction_label,
        'confidence': confidence,
        'probabilities': clf_probs.cpu().numpy()[0]
    }

    print(f"✅ Pipeline completed!")
    print(f"🎯 Prediction: {prediction_label} (Confidence: {confidence:.1%})")

    return results

print("✅ Pipeline function defined successfully!")

