    """Advanced training with mixup/cutmix"""
    model.train()
    running_loss = 0.0
    correct = 0
    total = 0

    pbar = tqdm(train_loader, desc=f"Training Epoch {epoch}")

    for images, labels, img_types in pbar:
        images = images.to(device, non_blocking=True)
        labels = labels.to(device, non_blocking=True).long()
        type_tensor = torch.tensor([0 if t == 'original' else 1 for t in img_types]).to(device)

        # Apply mixup/cutmix randomly
        r = np.random.rand(1)
        if use_mixup and r < 0.3:  # 30% chance mixup
            images, labels_a, labels_b, lam = mixup_data(images, labels, alpha=0.2)

            optimizer.zero_grad()
            outputs = model(images, type_tensor)
            loss = lam * criterion(outputs, labels_a) + (1 - lam) * criterion(outputs, labels_b)

        elif use_cutmix and r >= 0.7:  # 30% chance cutmix
            images, labels_a, labels_b, lam = cutmix_data(images, labels, alpha=1.0)

            optimizer.zero_grad()
            outputs = model(images, type_tensor)
            loss = lam * criterion(outputs, labels_a) + (1 - lam) * criterion(outputs, labels_b)

        else:
            # Normal training (40% of time)
            optimizer.zero_grad()
            outputs = model(images, type_tensor)
            loss = criterion(outputs, labels)

        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
        optimizer.step()

        running_loss += loss.item()
        _, predicted = torch.max(outputs.data, 1)
        total += labels.size(0)
        correct += (predicted == labels).sum().item()

        pbar.set_postfix({
            'Loss': f'{loss.item():.4f}',
            'Acc': f'{100*correct/total:.2f}%'
        })

    return running_loss/len(train_loader), 100*correct/total

