def apply_soft_mask(image, mask, alpha=0.3):
    """Apply soft masking - preserve background with lower intensity"""
    mask_float = mask.astype(np.float32)
    soft_mask = mask_float + (1 - mask_float) * alpha
    result = image * soft_mask
    return result.astype(np.uint8)

def apply_attention_mask(image, mask, min_weight=0.2):
    """Apply attention-based masking with smooth transitions"""
    mask_float = mask.astype(np.float32)
    mask_smooth = cv2.GaussianBlur(mask_float, (21, 21), 7)
    attention_map = min_weight + (1 - min_weight) * mask_smooth
    result = image * attention_map
    return result.astype(np.uint8)

class AdvancedXRayTransforms:
    """Advanced transforms with proper training flag"""
    def __init__(self, image_size=380, is_training=False):
        self.image_size = image_size
        self.is_training = is_training

        if is_training:
            self.transform = A.Compose([
               # Geometric transformations (mild for medical data)
                A.Rotate(limit=10, border_mode=cv2.BORDER_CONSTANT, value=0, p=0.7),
                A.ShiftScaleRotate(shift_limit=0.1, scale_limit=0.1, rotate_limit=10,
                                 border_mode=cv2.BORDER_CONSTANT, value=0, p=0.7),
                A.HorizontalFlip(p=0.5),  # Anatomically valid for chest X-rays

                # Intensity transformations (crucial for X-rays)
                A.RandomBrightnessContrast(brightness_limit=0.2, contrast_limit=0.2, p=0.8),
                A.RandomGamma(gamma_limit=(80, 120), p=0.5),
                A.CLAHE(clip_limit=2.0, tile_grid_size=(8, 8), p=0.5),  # Histogram equalization

                # Noise and blur (simulate real-world conditions)
                A.GaussNoise(var_limit=(10.0, 50.0), p=0.3),
                A.Blur(blur_limit=3, p=0.2),
                A.Resize(self.image_size, self.image_size),
                A.Normalize(mean=[0.5], std=[0.5]),
                ToTensorV2(),
            ])
        else:
            self.transform = A.Compose([
                A.Resize(self.image_size, self.image_size),
                A.Normalize(mean=[0.5], std=[0.5]),
                ToTensorV2(),
            ])

    def __call__(self, image):
        if isinstance(image, np.ndarray):
            if len(image.shape) == 3:
                image = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)
        else:
            image = np.array(image)

        # Apply CLAHE
        clahe = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(8,8))
        image = clahe.apply(image)

        transformed = self.transform(image=image)
        return transformed['image']




