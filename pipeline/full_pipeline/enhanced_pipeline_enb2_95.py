def run_enhanced_inference_adaptive(model, sgm_model, image_path):
    """Adaptive ensemble that weights based on individual confidence"""

    # Load and process image
    original_img = cv2.imread(image_path, cv2.IMREAD_GRAYSCALE)
    if original_img is None:
        return None

    # Generate segmentation
    seg_input = cv2.resize(original_img, (256, 256))
    seg_input = seg_input.astype(np.float32) / 255.0
    seg_input = np.expand_dims(seg_input, axis=(0, -1))

    mask_pred = sgm_model.predict(seg_input, verbose=0)
    mask_binary = (mask_pred[0, :, :, 0] > 0.5).astype(np.uint8)

    # Create different versions
    original_resized = cv2.resize(original_img, (256, 256))
    segmented_soft = apply_advanced_soft_mask(original_resized, mask_binary, alpha=0.2)
    segmented_attention = apply_attention_mask(original_resized, mask_binary)

    # Prepare inputs
    transform = AdvancedXRayTransforms(image_size=224, is_training=False)
    original_tensor = transform(original_resized).unsqueeze(0).to(device)
    segmented_soft_tensor = transform(segmented_soft).unsqueeze(0).to(device)
    segmented_att_tensor = transform(segmented_attention).unsqueeze(0).to(device)

    model.eval()
    with torch.no_grad():
        # Get predictions from all versions
        output_orig = model(original_tensor, torch.tensor([0]).to(device))
        output_soft = model(segmented_soft_tensor, torch.tensor([1]).to(device))
        output_att = model(segmented_att_tensor, torch.tensor([1]).to(device))

        probs_orig = F.softmax(output_orig, dim=1)
        probs_soft = F.softmax(output_soft, dim=1)
        probs_att = F.softmax(output_att, dim=1)

        # Calculate adaptive weights based on confidence
        conf_orig = probs_orig.max().item()
        conf_soft = probs_soft.max().item()
        conf_att = probs_att.max().item()

        # Normalize weights
        total_conf = conf_orig + conf_soft + conf_att
        w_orig = conf_orig / total_conf
        w_soft = conf_soft / total_conf
        w_att = conf_att / total_conf

        # Adaptive ensemble
        ensemble_probs = w_orig * probs_orig + w_soft * probs_soft + w_att * probs_att
        pred_class = ensemble_probs.argmax(1).item()
        confidence = ensemble_probs.max(1)[0].item()

    return {
        'prediction': ['Normal', 'Abnormal'][pred_class],
        'confidence': confidence,
        'weights': {'original': w_orig, 'soft': w_soft, 'attention': w_att},
        'individual_confidences': {'original': conf_orig, 'soft': conf_soft, 'attention': conf_att}
    }


